function applySiteLanguage(language) {
    const selectedLanguage = siteTranslations[language] ? language : "en";
    localStorage.setItem("agentLanguage", selectedLanguage);
    document.documentElement.lang = selectedLanguage === "zh" ? "zh-Hant" : "en";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = siteTranslations[selectedLanguage][element.dataset.i18n];

        if (value) {
            element.textContent = value;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const value = siteTranslations[selectedLanguage][element.dataset.i18nPlaceholder];

        if (value) {
            element.placeholder = value;
        }
    });

    document.querySelectorAll("[data-agent-language]").forEach((button) => {
        const isActive = button.dataset.agentLanguage === selectedLanguage;
        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", isActive ? "true" : "false");
    });

    window.dispatchEvent(new CustomEvent("osuCoursePathLanguageChanged", {
        detail: { language: selectedLanguage }
    }));
}

document.querySelectorAll("[data-agent-language]").forEach((button) => {
    button.addEventListener("click", () => {
        applySiteLanguage(button.dataset.agentLanguage);
    });
});

applySiteLanguage(localStorage.getItem("agentLanguage") || "en");
